export type TaskrunnerMessageKey = keyof typeof messages.vi;
export type TaskrunnerTranslator = (key: TaskrunnerMessageKey, ...args: MessageArgument[]) => string;

export function taskrunnerText(language: Language, key: TaskrunnerMessageKey, ...args: MessageArgument[]): string {
  const dictionary = messages[language] as Record<TaskrunnerMessageKey, MessageValue>;
  const value = dictionary[key] ?? messages.vi[key];
  return typeof value === "function" ? value(...args) : value;
}

export function useTaskrunnerText(): TaskrunnerTranslator {
  const { language } = useLanguage();
  return useCallback((key, ...args) => taskrunnerText(language, key, ...args), [language]);
}
