export type TooltipMessageKey = keyof typeof messages.vi;
export type TooltipTranslator = (key: TooltipMessageKey, ...args: MessageArgument[]) => string;

export function tooltipText(language: Language, key: TooltipMessageKey, ...args: MessageArgument[]): string {
  const dictionary = messages[language] as Record<TooltipMessageKey, MessageValue>;
  const value = dictionary[key] ?? messages.vi[key];
  return typeof value === "function" ? value(...args) : value;
}

export function useTooltipText(): TooltipTranslator {
  const { language } = useLanguage();
  return useCallback((key, ...args) => tooltipText(language, key, ...args), [language]);
}
