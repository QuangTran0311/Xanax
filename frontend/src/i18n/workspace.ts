export type WorkspaceMessageKey = keyof typeof messages.vi;
export type WorkspaceTranslator = (key: WorkspaceMessageKey, ...args: MessageArgument[]) => string;

export function workspaceText(language: Language, key: WorkspaceMessageKey, ...args: MessageArgument[]): string {
  const dictionary = messages[language] as Record<WorkspaceMessageKey, MessageValue>;
  const value = dictionary[key] ?? messages.vi[key];
  return typeof value === "function" ? value(...args) : value;
}

export function useWorkspaceText(): WorkspaceTranslator {
  const { language } = useLanguage();
  return useCallback((key, ...args) => workspaceText(language, key, ...args), [language]);
}
